"""Generate ds/apps/DA-ESS-ContentUpdate/local/savedsearches.conf: enable the chosen ESCU detections
as normal tracked alerts on plain Splunk Enterprise (no Enterprise Security).

usage: python -I -X utf8 tools/splunk-uf/escu_enable.py <sse.tgz> <final-list.txt>

Per detection: disabled=0, hourly at its own minute (spread over the hour; ESCU's window
-70m@m..-10m@m stays, so consecutive runs are contiguous), ES-only actions risk/notable off,
alert.track=1 (Activity > Triggered Alerts), alert.severity from the research risk_severity,
one alert per run (digest). Everything not listed stays disabled (ESCU default).
"""
import json
import sys
import tarfile
from pathlib import Path

SSE, LIST = sys.argv[1], Path(sys.argv[2])
OUT = Path(__file__).resolve().parent / "ds" / "apps" / "DA-ESS-ContentUpdate" / "local" / "savedsearches.conf"
SEV = {"critical": 6, "high": 5, "medium": 4, "low": 3, "informational": 2}

with tarfile.open(SSE, "r:*") as tf:
    meta = json.load(tf.extractfile("Splunk_Security_Essentials/appserver/static/vendor/splunk/Splunk_Research_Detections.json"))
meta = {m["name"]: m for m in (meta if isinstance(meta, list) else meta.get("detections", meta)) if isinstance(m, dict)}

names = [n.strip() for n in LIST.read_text(encoding="utf-8-sig").splitlines() if n.strip() and not n.startswith("#")]
out = ["# Lab Console (generated by tools\\splunk-uf\\escu_enable.py from escu_enabled.txt - edit the list, re-run).",
       "# ESCU detections enabled on plain Splunk Enterprise: ES-only actions (risk, notable) off, normal",
       "# tracked alerts instead. Each runs hourly at its own minute (spread for the 4-core SIEM).",
       "# Tuning: override the detection's `<name>_filter` macro in local/macros.conf, not the search.", ""]
for i, st in enumerate(names):
    d = meta.get(st.removeprefix("ESCU - ").removesuffix(" - Rule"), {})
    minute = (2 + i * 60 // max(len(names), 1)) % 60
    mitre = ",".join((d.get("tags") or {}).get("mitre_attack_id") or [])
    out += [f"[{st}]",
            f"# {d.get('risk_severity', '?')} | {mitre}",
            "disabled = 0", "enableSched = 1", f"cron_schedule = {minute} * * * *", "allow_skew = 0",
            # action.correlationsearch.enabled stays at ESCU's 1: it's only a label without ES, but
            # Security Essentials hides ESCU searches that aren't labelled correlation searches.
            "action.risk = 0", "action.notable = 0",
            "alert.track = 1", f"alert.severity = {SEV.get(d.get('risk_severity', ''), 4)}",
            "alert.digest_mode = 1", "alert.expires = 7d",
            "counttype = number of events", "relation = greater than", "quantity = 0", ""]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(names)} detections)")
